/** Возвращает подсказку для виджета: для KPI — по метрике из config,
 * иначе по типу виджета. undefined, если подсказки нет. */
export function getWidgetHint(
  widgetType: string,
  config?: Record<string, unknown>,
): string | undefined {
  if (widgetType === 'kpi_card') {
    const metric = config?.metric;
    if (typeof metric === 'string' && KPI_METRIC_HINTS[metric]) {
      return KPI_METRIC_HINTS[metric];
    }
    return WIDGET_HINTS.kpi_card;
  }
  return WIDGET_HINTS[widgetType];
}
